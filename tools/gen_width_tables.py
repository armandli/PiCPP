#!/usr/bin/env python3
"""Generate src/util/width_tables.h from the Unicode Character Database.

Downloads the latest UCD files from unicode.org and writes the interval tables
used by pi::util::display_width(). Re-run whenever a new Unicode version ships:

    python3 tools/gen_width_tables.py
"""

import re
import sys
import urllib.request
from pathlib import Path

UCD = "https://www.unicode.org/Public/UCD/latest/ucd/"
OUT = Path(__file__).resolve().parent.parent / "src" / "util" / "width_tables.h"

LINE = re.compile(r"^([0-9A-Fa-f]+)(?:\.\.([0-9A-Fa-f]+))?\s*;\s*([A-Za-z_]+)")


def fetch(name):
    with urllib.request.urlopen(UCD + name) as resp:
        return resp.read().decode("utf-8")


def version(text):
    m = re.search(r"-(\d+\.\d+\.\d+)\.txt", text.splitlines()[0])
    return m.group(1) if m else "unknown"


def ranges(text, wanted):
    out = []
    for line in text.splitlines():
        m = LINE.match(line)
        if m and m.group(3) in wanted:
            first = int(m.group(1), 16)
            last = int(m.group(2), 16) if m.group(2) else first
            out.append((first, last))
    return out


def merge(intervals):
    merged = []
    for first, last in sorted(intervals):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def subtract(intervals, cp):
    out = []
    for first, last in intervals:
        if first <= cp <= last:
            if first < cp: out.append((first, cp - 1))
            if cp < last: out.append((cp + 1, last))
        else:
            out.append((first, last))
    return out


def emit(name, comment, intervals):
    rows = []
    for i in range(0, len(intervals), 3):
        rows.append("  " + " ".join("{0x%04X, 0x%04X}," % iv for iv in intervals[i:i + 3]))
    return "// %s\ninline constexpr Interval %s[] = {\n%s\n};\n" % (comment, name, "\n".join(rows))


def main():
    eaw = fetch("EastAsianWidth.txt")
    gc = fetch("extracted/DerivedGeneralCategory.txt")
    emoji = fetch("emoji/emoji-data.txt")
    ver = version(eaw)

    zero = ranges(gc, {"Mn", "Me", "Cf"})
    zero += [(0x1160, 0x11FF), (0xD7B0, 0xD7FF), (0x200B, 0x200B)]
    zero = merge(subtract(merge(zero), 0x00AD))

    wide = ranges(eaw, {"W", "F"})
    # default-W blocks: unassigned code points here are still wide
    wide += [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
             (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]
    wide = merge(wide)

    pictographic = merge(ranges(emoji, {"Extended_Pictographic"}))

    header = f"""// Generated by tools/gen_width_tables.py from Unicode {ver} -- do not edit.
#ifndef UTIL_WIDTH_TABLES_H
#define UTIL_WIDTH_TABLES_H

namespace pi::util::detail {{

struct Interval {{
  char32_t first;
  char32_t last;
}};

{emit("ZERO_WIDTH", "Mn, Me, Cf (except U+00AD), Hangul Jamo medial/final, U+200B: 0 cells", zero)}
{emit("WIDE", "East Asian Wide (W) and Fullwidth (F): 2 cells", wide)}
{emit("EXTENDED_PICTOGRAPHIC", "Extended_Pictographic: emoji that can be joined by ZWJ", pictographic)}
}}  // namespace pi::util::detail

#endif  // UTIL_WIDTH_TABLES_H
"""
    OUT.write_text(header)
    print(f"Unicode {ver}: ZERO_WIDTH={len(zero)} WIDE={len(wide)} "
          f"EXTENDED_PICTOGRAPHIC={len(pictographic)} -> {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
